// Generates converter-consumable barrel entries for @zenncore/web.
//
// Why this exists: the package ships per-component dist outputs
// (dist/components/<name>/index.{js,d.ts}) via wildcard `exports`, with no
// `.`/`module`/`types` entry and no barrel. The design-sync converter needs a
// single JS entry (for the runtime window.* bundle) and a single .d.ts entry
// reachable via package.json `types` (for component discovery + prop
// extraction). This script synthesizes both, deterministically, from whatever
// is currently in dist/ — so a re-sync reproduces identical inputs.
//
// Card model (flat-sibling DS): the package exports each compound family flat
// — `Accordion`, `AccordionItem`, `AccordionPanel`, … as siblings (NOT
// `Accordion.Item`). To get one card per family (43) instead of ~250 cards for
// every sub-part — and without fabricating a dotted API the package doesn't
// actually ship — the DTS barrel re-exports ONLY the family roots, while the
// JS barrel `export *`s everything so sub-parts stay importable from the
// window global for real compositions.
//
// Run from the repo root: `node .design-sync/gen-entry.mjs`

import {
  existsSync,
  lstatSync,
  readdirSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PKG_DIR = join(REPO_ROOT, "packages/web");
const DIST = join(PKG_DIR, "dist");
const COMPONENTS_DIR = join(DIST, "components");

const pascal = (kebab) =>
  kebab
    .split(/[^a-z0-9]+/i)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

// PascalCase value exports declared in a component module's index.d.ts.
const exportedPascalNames = (dtsPath) => {
  const text = readFileSync(dtsPath, "utf8");
  const names = new Set();
  // `export { A, B, C };` blocks (tsdown emits a single trailing block).
  for (const block of text.matchAll(/export\s*\{([^}]*)\}/g)) {
    for (const raw of block[1].split(",")) {
      const name = raw
        .trim()
        .split(/\s+as\s+/)
        .pop()
        ?.trim();
      if (name && /^[A-Z][A-Za-z0-9]*$/.test(name)) names.add(name);
    }
  }
  return [...names];
};

// Family root for a directory: the export equal to PascalCase(dir) when it
// exists, else the shortest PascalCase export (the prefix the others extend,
// e.g. otp-input → InputOTP, which prefixes InputOTPGroup/Slot/Separator).
const rootFor = (dir, names) => {
  const ideal = pascal(dir);
  if (names.includes(ideal)) return ideal;
  const byLength = [...names].sort(
    (a, b) => a.length - b.length || a.localeCompare(b),
  );
  return byLength[0] ?? null;
};

const dirs = readdirSync(COMPONENTS_DIR, { withFileTypes: true })
  .filter(
    (entry) =>
      entry.isDirectory() &&
      existsSync(join(COMPONENTS_DIR, entry.name, "index.d.ts")),
  )
  .map((entry) => entry.name)
  .sort();

const roots = [];
const jsLines = [];
const dtsLines = [];
for (const dir of dirs) {
  const rel = `./components/${dir}/index.js`;
  jsLines.push(`export * from ${JSON.stringify(rel)};`);
  const names = exportedPascalNames(join(COMPONENTS_DIR, dir, "index.d.ts"));
  const root = rootFor(dir, names);
  if (!root) {
    console.error(
      `! ${dir}: no PascalCase export found — skipping from DTS barrel`,
    );
    continue;
  }
  roots.push(root);
  dtsLines.push(`export { ${root} } from ${JSON.stringify(rel)};`);
}

const banner =
  "// AUTO-GENERATED by .design-sync/gen-entry.mjs — do not edit by hand.\n";
writeFileSync(join(DIST, "index.js"), `${banner + jsLines.join("\n")}\n`);
writeFileSync(join(DIST, "index.d.ts"), `${banner + dtsLines.join("\n")}\n`);

// Point package.json at the barrels so the converter's findTypesRoot/entry
// resolution lands on them. Idempotent: only writes when a field differs.
const pkgPath = join(PKG_DIR, "package.json");
const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
let patched = false;
for (const [key, value] of [
  ["module", "./dist/index.js"],
  ["types", "./dist/index.d.ts"],
]) {
  if (pkg[key] !== value) {
    pkg[key] = value;
    patched = true;
  }
}
if (patched) writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);

// Ensure react-dom is resolvable from the DS package's node_modules. The lib
// declares react (peer) but NOT react-dom — that's the host app's peer — so
// the converter's vendorReact + preview runtime can't find it. Resolve the
// real react-dom (from the app that does depend on it) and symlink it in.
const ensureReactDom = () => {
  const target = join(PKG_DIR, "node_modules/react-dom");
  if (existsSync(target)) return "already linked";
  const require = createRequire(join(REPO_ROOT, "apps/web/package.json"));
  let resolved;
  try {
    resolved = dirname(require.resolve("react-dom/package.json"));
  } catch {
    return "react-dom not resolvable from apps/web — install it or link manually";
  }
  try {
    if (lstatSync(target, { throwIfNoEntry: false }))
      rmSync(target, { recursive: true, force: true });
  } catch {}
  symlinkSync(resolved, target, "dir");
  return `linked → ${resolved}`;
};
const reactDomStatus = ensureReactDom();

console.error(`gen-entry: ${dirs.length} dirs → ${roots.length} family roots`);
console.error(`  roots: ${roots.join(", ")}`);
console.error(
  `  package.json ${patched ? "patched (module/types)" : "already pointed at barrels"}`,
);
console.error(`  react-dom: ${reactDomStatus}`);
